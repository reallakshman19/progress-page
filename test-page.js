// Optional per-project Test page. Synthetic interaction stays in browser memory.
// Never a live Timeline event, published audit, Cycle receipt, or authority.
import { el, link, copyText } from './util.js?v=33';
import { smartBadgesForScope, smartBadgeText, renderSmartBadges } from './smart-badges.js?v=33';
import { autoGeneratedTimelineCards } from './timeline-live.js?v=33';

const MODES=Object.freeze(['ACTION','INFO','INFO_AUTO']);
const trustedUrl=u=>/^https:\/\/github\.com\/[a-z0-9_.-]+\/[a-z0-9_.-]+(?:\/|$)/i.test(u||'')?u:null;

export function testPageModel(project,{cardId=null,mode='ACTION',needsOwner=false}={}) {
  const index=project?.index||{},milestones=index.milestones||{},cards=project?.cards||{};
  const key=index.project?.key||'UNRECORDED';
  const choices=Object.entries(cards).filter(([,c])=>!!c&&!c.closed&&
    !!milestones[c.milestone]?.wbs).map(([id,c])=>({
      id,label:c.label||id,wbs:milestones[c.milestone].wbs,
      milestoneId:c.milestone
    }));
  const selected=choices.find(c=>c.id===cardId)||choices[0]||null;
  const chosenMode=MODES.includes(mode)?mode:'ACTION';
  const badges=selected?smartBadgesForScope(project,{
    cardId:selected.id,milestoneId:selected.milestoneId
  }):smartBadgesForScope(project);
  const published=autoGeneratedTimelineCards(project,20).filter(c=>
    !selected||c.card===selected.id||c.wbs===selected.wbs);
  const first=published[0]||null;
  const wbs=selected?.wbs||'UNSCOPED';
  const title=selected?.label||'Unscoped sample handoff';
  const thread='demo/'+key+'/'+(selected?.id||'unscoped');
  const source=selected?trustedUrl(cards[selected.id]?.src):null;
  const owner=chosenMode==='ACTION'&&needsOwner;
  const stage=chosenMode==='ACTION'?(owner?'NEEDS_OWNER':'OPEN'):
    chosenMode==='INFO'?'HANDED_OFF':'SOURCE_RECORDED';
  const description=chosenMode==='ACTION'
    ?'Demonstration: Coder has one scoped communication step to the independent reviewer.'
    :chosenMode==='INFO'
      ?'Demonstration: Reviewer acknowledged the handoff. Independent review remains open; no PASS was established.'
      :first?.details||'No source-backed published WBS audit record for this selection.';
  return {key,title,choices,selected,wbs,badges,mode:chosenMode,stage,thread,
    source,needsOwner:owner,description,first,published,
    isDemo:chosenMode!=='INFO_AUTO',canCopy:chosenMode!=='INFO_AUTO'||!!first};
}

export function testPagePacket(model) {
  const lines=['TEST PAGE — DEMONSTRATION ONLY; NOT A LIVE EVENT OR TASK RETURN',
    'Project: '+model.key,'Scenario: '+model.mode+' / '+model.stage,
    'WBS: '+model.wbs,'Card: '+(model.selected?.id||'UNSCOPED'),
    'Thread: '+model.thread,'Summary: '+model.description,
    'Original task context source: '+(model.source||'NOT_RECORDED'),
    'Smart Badge identifiers:',smartBadgeText(model.badges)||'NOT_RECORDED'];
  if(model.mode==='INFO_AUTO'&&model.first){
    lines.push('Actual Page audit event: '+model.first.auditId,
      'Revision: '+model.first.revision,'Recorded at: '+model.first.at,
      'Original audit source: '+model.first.source);
  }
  lines.push('BOUNDARY: This text is a sandbox demonstration, not a production Cycle, Page audit, engineering acceptance or agent assignment. Use original source records for real work.');
  return lines.join('\n');
}

export function renderTestPage(root,project,{historical=false}={}) {
  let current={mode:'ACTION',cardId:null,needsOwner:false};
  const wrapper=el('section','demo-page');
  wrapper.append(el('h3',null,'Test page · Project demonstration'),
    el('p','demo-safety','DEMO ONLY — local controls cannot publish to Timeline, modify Page/Cycle JSON, dispatch an agent, acknowledge an assignment or establish independent engineering PASS. Test cases are separate from production status.'));
  if(historical)wrapper.append(el('p','muted',
    'Historical project snapshot: context comes from this recorded revision, not current live agent status.'));
  const controls=el('div','demo-controls');
  const scope=el('label',null,'Recorded task context');
  const select=el('select');
  select.setAttribute('aria-label','Select recorded task for demonstration');
  const stage=el('div','demo-stage');
  const ask=el('button','btn small','Simulate Owner attention: OFF');
  ask.type='button';
  ask.addEventListener('click',()=>{
    current.needsOwner=!current.needsOwner;
    ask.textContent='Simulate Owner attention: '+(current.needsOwner?'ON':'OFF');
    update();
  });
  const preview=el('div','demo-preview');
  const model0=testPageModel(project);
  for(const task of model0.choices){
    const option=el('option',null,task.wbs+' · '+task.label);
    option.value=task.id;select.append(option);
  }
  if(!model0.choices.length) {
    const option=el('option',null,'No recorded WBS task; unscoped demonstration only');
    option.value='';select.append(option);select.disabled=true;
  }
  select.addEventListener('change',()=>{current.cardId=select.value||null;update();});
  scope.append(select);controls.append(scope);
  for(const [mode,label] of [['ACTION','Action'],['INFO','Info · reviewer handoff'],['INFO_AUTO','INFO-Auto generated']]){
    const btn=el('button','btn small',label);btn.type='button';
    btn.dataset.mode=mode;
    btn.addEventListener('click',()=>{current.mode=mode;update();});
    stage.append(btn);
  }
  controls.append(stage,ask);
  const panel=el('div');
  panel.append(controls,preview);
  wrapper.append(panel);root.append(wrapper);
  function update(){
    const model=testPageModel(project,current);
    preview.replaceChildren();
    for(const b of stage.querySelectorAll('button'))b.setAttribute('aria-pressed',String(b.dataset.mode===model.mode));
    ask.disabled=model.mode!=='ACTION';
    const box=el('article','demo-card '+(model.mode==='ACTION'?'action':model.mode==='INFO'?'info':'auto'));
    const top=el('div','demo-card-head');
    top.append(el('span','chip',model.mode==='INFO_AUTO'?'INFO-Auto generated':model.mode),
      el('span','chip',model.stage),el('span','muted','TEST ONLY · '+model.wbs));
    box.append(top,el('h4',null,model.title),el('p',null,model.description));
    if(model.needsOwner)box.append(el('p','ct-owner','Simulated Needs Owner: choose an available reviewer. No real request is sent.'));
    if(model.mode==='INFO')box.append(el('p','muted','History: ACTION (synthetic) → INFO/HANDED_OFF (synthetic). IR work is a separate open task.'));
    if(model.mode==='INFO_AUTO'){
      if(model.first){
        box.append(el('p','muted','Actual recorded Page evidence: '+model.first.auditId+
          ' · '+model.first.revision+' · '+model.first.at+' · recorded actor '+model.first.actor));
        box.append(link(model.first.source,'Open original audit evidence'));
      } else {
        box.append(el('p','muted','No qualifying audit entry. Unknown is not a completed task or a missing report.'));
      }
    } else if(model.source)box.append(link(model.source,'Open original task context'));
    renderSmartBadges(box,model.mode==='INFO_AUTO'&&model.first?
      model.first.badges:model.badges);
    if(model.mode==='INFO_AUTO'&&model.published.length>1)
      box.append(el('p','muted',model.published.length+' matching published observations available; newest shown. No synthetic audit generated.'));
    const packet=el('button','btn small','Copy demonstration packet');
    packet.type='button';packet.disabled=!model.canCopy;
    packet.addEventListener('click',()=>copyText(testPagePacket(model),packet));
    box.append(packet,el('p','muted demo-mono','Thread '+model.thread+
      ' · Identifier source: published project WBS/AIM and audit records only'));
    preview.append(box);
  }
  update();
}
