// This only reads the *existing* published TopoFix Page index/cards/audit.
// The new native task issue is not itself an assigned published Page card.
export function topoOperationalContextModel(key,project,pageFetch=null){
 const scope=TOPO_WBS_SCOPE[key];
 if(!scope)throw Error('Unknown Adhoc project');
 const valid=project?.index?.project?.key==='topofix'&&
   project?.cards&&typeof project.cards==='object'&&Array.isArray(project?.audit?.events);
 const status=!valid?'UNKNOWN':pageFetch?.status==='ok'?'LIVE_READ':
   pageFetch?.status==='offline'?'OFFLINE_SNAPSHOT':'READ_NOT_VERIFIED';
 const blank={schema:'cycle-board.adhoc-operational/v1',status,scope,
   revision:'UNKNOWN',aim:null,aimSrc:null,wbs:[],infoCount:0,
   nativeAssignmentMapping:'UNMAPPED'};
 if(!valid)return blank;
 const index=project.index,milestones=index.milestones||{},
   cards=project.cards||{},current=(index.revisions||[]).find(r=>r.status==='current');
 const wbs=scope.map(number=>{
   const item=Object.entries(milestones).find(([,m])=>m.wbs===number);
   const milestoneId=item?.[0]||null,m=item?.[1]||null;
   const found=Object.entries(cards).find(([,c])=>c.milestone===milestoneId&&!c.closed);
   const card=found?.[1]||null;
   return {wbs:number,milestoneId,title:m?.name||'WBS not published',
     full:m?.full||null,capability:m?.cap||'UNKNOWN',canDo:m?.canDo||null,
     recordedState:card?.state||'NOT_RECORDED',recordedNext:card?.next?.text||null,
     recordedActor:card?.next?.actor||'UNKNOWN',recordedNow:card?.now||null,
     source:card?.src||m?.capSrc||null};
 });
 return {...blank,revision:current?.id||'UNKNOWN',aim:index.project.aim||null,
   aimSrc:index.project.aimSrc||null,wbs,
   infoCount:autoGeneratedTimelineCards(project,1000).filter(x=>scope.includes(x.wbs)).length};
}

