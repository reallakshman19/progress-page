import assert from 'node:assert/strict';
import test from 'node:test';
import {readFileSync} from 'node:fs';
import {smartBadgesForScope,smartBadgeText} from '../smart-badges.js';
import {agentStartModel,agentStartTaskText} from '../agent-start.js';
import {wbsGroups} from '../progress.js';
import {oracleContinuityModel} from '../oracle-continuity.js';
import {autoGeneratedTimelineCards,autoGeneratedPageBrief} from '../timeline-live.js';

const get=file=>JSON.parse(readFileSync(new URL('../data/ciifr/'+file+'.json',import.meta.url),'utf8'));
const page={index:get('index'),cards:get('cards'),audit:get('audit'),fixtures:get('fixtures')};
const SRC='https://github.com/reallakshman19/XML_Compare_Utilities/issues/180';

test('AIM, milestone ROADMAP and WBS badges share stable IDs and original sources',()=>{
 const b=smartBadgesForScope(page,{cardId:'geo-g1',milestoneId:'M13'});
 assert.deepEqual(b.map(x=>x.type),['AIM','WBS','ROADMAP']);
 assert.deepEqual(b.map(x=>x.id),[
   'ciifr/AIM/project','ciifr/WBS/3.1','ciifr/ROADMAP/M13']);
 assert.ok(b.every(x=>x.source?.startsWith('https://github.com/')));
 assert.ok(b.every(x=>x.evidence==='SOURCE_LINKED'));
 assert.match(smartBadgeText(b),/ciifr\/WBS\/3\.1/);
 assert.match(smartBadgeText(b),/index.milestones.M13/);
});
test('Plan and Fixture tags are conditional on original audited kind, not free-text claims',()=>{
 const base={source:SRC,id:'CIIFR-R-0111'};
 const regular=smartBadgesForScope(page,{cardId:'geo-g1',event:{...base,kind:'UPDATE',summary:'Plan and fixture accepted'}});
 assert.deepEqual(regular.map(x=>x.type),['AIM','WBS','ROADMAP']);
 const plan=smartBadgesForScope(page,{cardId:'geo-g1',event:{...base,kind:'PLAN'}});
 assert.deepEqual(plan.map(x=>x.type),['AIM','WBS','ROADMAP','PLAN']);
 const fixture=smartBadgesForScope(page,{cardId:'geo-g1',event:{...base,kind:'FIXTURE',list:'pending'}});
 assert.deepEqual(fixture.map(x=>x.type),['AIM','WBS','ROADMAP','FIXTURE']);
 assert.match(smartBadgeText(fixture),/SOURCE_LINKED/);
});
test('Wrong WBS, nonexistent task and unavailable aim source fail without invented associations',()=>{
 assert.deepEqual(smartBadgesForScope(page,{cardId:'geo-g1',milestoneId:'M12'}),[]);
 assert.deepEqual(smartBadgesForScope(page,{cardId:'does-not-exist'}),[]);
 const isolated={index:{project:{key:'draft',aim:'Private Owner AIM',aimSrc:'OWNER_PRIVATE_REF:test'},milestones:{}},cards:{}};
 const aim=smartBadgesForScope(isolated);
 assert.equal(aim[0].id,'draft/AIM/project');
 assert.equal(aim[0].source,null);
 assert.equal(aim[0].evidence,'SOURCE_UNAVAILABLE');
});
test('Exact selected Agent Start task includes reusable IDs; no assignment is granted',()=>{
 const family=wbsGroups(page.index).find(x=>x.key==='wbs:3');
 const m=agentStartModel(page,{family,step:'M13',cardId:'geo-g1',revision:'R4'});
 assert.equal(m.selected?.id,'geo-g1');
 assert.deepEqual(m.selected.smartBadges.map(x=>x.type),['AIM','WBS','ROADMAP']);
 const packet=agentStartTaskText(m);
 assert.match(packet,/ciifr\/AIM\/project/);
 assert.match(packet,/ciifr\/WBS\/3\.1/);
 assert.match(packet,/not an acknowledged assignment/);
 assert.deepEqual(smartBadgesForScope({...page,cards:{}},{cardId:'geo-g1'}),[]);
});
test('INFO Auto generates same badge identity for Page writer without changing audit',()=>{
 const original=JSON.stringify(page.audit);
 const items=autoGeneratedTimelineCards(page,30);
 const g1=items.find(x=>x.card==='geo-g1');
 assert.ok(g1);
 assert.deepEqual(g1.badges.map(x=>x.id),smartBadgesForScope(page,{cardId:'geo-g1',milestoneId:'M13',
   event:page.audit.events.find(x=>x.id===g1.auditId)}).map(x=>x.id));
 const brief=autoGeneratedPageBrief(g1);
 assert.match(brief,/ciifr\/WBS\/3\.1/);
 assert.match(brief,/ciifr\/AIM\/project/);
 assert.equal(JSON.stringify(page.audit),original,'no duplicate report or Page data mutation');
});
test('Oracle continuity only adds badge to recorded Oracle handover, not coder G0',()=>{
 const p={index:{project:{key:'demo'},milestones:{M1:{wbs:'1',name:'Control handover',
   capSrc:'https://github.com/example/repo/issues/2'}},groups:{control:{title:'Oracle continuity'}}},
   cards:{coder:{group:'control',milestone:'M1',label:'Builder onboarding',who:{role:'Coder'},
     src:SRC},
     oracle:{group:'control',milestone:'M1',label:'Oracle handover',
       who:{role:'Oracle'},state:'IN_PROGRESS',src:SRC}},audit:{events:[]}};
 const m=oracleContinuityModel(p);
 assert.deepEqual(m.cards.map(c=>c.id),['oracle']);
 assert.ok(m.cards[0].smartBadges.some(x=>x.id==='demo/ORACLE_CONTINUITY/oracle'));
 assert.ok(m.cards[0].smartBadges.some(x=>x.id==='demo/WBS/1'));
});
