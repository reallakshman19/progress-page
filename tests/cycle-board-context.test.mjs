import assert from 'node:assert/strict';
import test from 'node:test';
import { readFileSync } from 'node:fs';
import { boardSourceConfigured,loadBoardNative,cycleBoardContextModel,
  renderCycleBoardContext } from '../cycle-board-context.js';
import { autoGeneratedTimelineCards,renderCycleTimeline } from '../timeline-live.js';

const page={
 index:JSON.parse(readFileSync(new URL('../data/ciifr-node/index.json',import.meta.url),'utf8')),
 cards:JSON.parse(readFileSync(new URL('../data/ciifr-node/cards.json',import.meta.url),'utf8')),
 audit:JSON.parse(readFileSync(new URL('../data/ciifr-node/audit.json',import.meta.url),'utf8'))
};
const projectKey='ciifr-node';
const original=JSON.stringify(page);
const rev='7f5dc773ac7bb08544d086be734e4337295088a0';
const expectedApi='https://api.github.com/repos/reallakshman19/XML_Compare_Utilities/';
function nativeMock(url){
 const num=Number(url.split('/').at(-1));
 if(url.includes('/pulls/')){
   return {number:num,html_url:'https://github.com/reallakshman19/XML_Compare_Utilities/pull/'+num,
     title:'[DRAFT] R0 repair',head:{sha:rev},draft:true,state:'open',
     merged_at:null,updated_at:'2026-10-29T01:00:00Z',
     body:'SELF_ASSESSED; independent review pending; GATE_R0 HOLD'};
 }
 return {number:num,html_url:'https://github.com/reallakshman19/XML_Compare_Utilities/issues/'+num,
   title:'Owner-directed native repair',state:'open',
   updated_at:'2026-10-29T02:00:00Z',
   body:'SELF_ASSESSED and GATE_R0 HOLD; fresh non-author review pending'};
}
function fetchMock(url){
 assert.ok(url.startsWith(expectedApi));
 return Promise.resolve({ok:true,status:200,json:async()=>nativeMock(url)});
}
function fakeElement(tag){
 return {tag,className:'',title:'',children:[],attributes:{},text:'',
  set textContent(s){this.text=String(s);this.children=[];},
  get textContent(){return this.text+this.children.map(n=>typeof n==='string'?n:n.textContent).join('');},
  append(...items){this.children.push(...items);},
  setAttribute(k,v){this.attributes[k]=String(v);},
  addEventListener(){},querySelectorAll(){return[];},replaceChildren(...items){this.children=items;}
 };
}
function withFakeDom(fn){
 const prior=globalThis.document;
 globalThis.document={createElement:fakeElement};
 try{return fn();}finally{globalThis.document=prior;}
}
test('CT-1 reads exact configured native sources once with deterministic source-head identities',async()=>{
 const one=await loadBoardNative(projectKey,fetchMock,()=> '2026-10-29T09:00:00Z');
 const two=await loadBoardNative(projectKey,fetchMock,()=> '2026-10-29T09:02:00Z');
 assert.equal(one.status,'ok');assert.equal(one.failures.length,0);
 assert.equal(one.observations.length,2);
 const pr=one.observations.find(x=>x.number===232);
 assert.equal(pr.revision,rev);
 assert.equal(pr.occurrenceId,'github:reallakshman19/XML_Compare_Utilities:pull-head:232:'+rev);
 assert.equal(pr.qualification,'SELF_ASSESSED');
 assert.equal(pr.reportedHold,true);
 assert.equal(pr.technicalPass,'NOT_ESTABLISHED');
 assert.deepEqual(one.observations.map(x=>x.occurrenceId),two.observations.map(x=>x.occurrenceId));
 assert.notEqual(one.observedAt,two.observedAt,'observation time changes but occurrence ID is stable');
 assert.equal(JSON.stringify(page),original);
});
test('CT-1 uses existing published WBS 2/Page audit, but does not create a Cycle assignment',async()=>{
 const source=await loadBoardNative(projectKey,fetchMock,()=> '2026-10-29T09:00:00Z');
 const auto=autoGeneratedTimelineCards(page);
 const context=cycleBoardContextModel(page,{native:source,autoCards:auto,cycleStatus:'UNMAPPED',
   pageFetch:{status:'ok',observedAt:'2026-10-29T08:55:00Z'}});
 assert.equal(context.schema,'cycle-board.context/v1');
 assert.equal(context.project,projectKey);
 assert.equal(context.cycle.status,'UNMAPPED');
 assert.equal(context.cycle.authority,'NOT_ESTABLISHED');
 assert.equal(context.native.coverage,'COMPLETE');
 assert.ok(context.autoCount>0,'source-backed Page audit does not depend on live intake');
 assert.ok(context.sources.every(x=>x.wbs==='2'&&x.scope==='SOURCE_MATCHED'));
 assert.ok(context.sources.some(x=>x.badges.some(b=>b.id==='ciifr-node/WBS/2')));
 assert.match(context.sources.find(x=>x.number===232).source,/pull\/232$/);
 assert.ok(context.page.latestId,'published Page audit original ID');
 assert.equal(JSON.stringify(page),original);
});
test('CT-1 displays native and INFO-Auto for no-live-intake project and retains legacy route semantics',async()=>{
 const source=await loadBoardNative(projectKey,fetchMock,()=> '2026-10-29T09:00:00Z');
 withFakeDom(()=>{
   const node=fakeElement('main');
   renderCycleTimeline(node,page,{status:'not_configured'},
     {native:source,cycleStatus:'UNMAPPED',pageFetch:{status:'ok',observedAt:'2026-10-29T09:00:00Z'}});
   assert.match(node.textContent,/Cycle Board/);
   assert.match(node.textContent,/WBS 2/);
   assert.match(node.textContent,/SOURCE_RECORDED|INFO-Auto generated/);
   assert.match(node.textContent,/PR #232/);
   assert.match(node.textContent,/SELF_ASSESSED/);
   assert.match(node.textContent,/GATE_R0 HOLD/);
   assert.match(node.textContent,/Canonical Cycle.*UNMAPPED/);
   assert.match(node.textContent,/No optional live-comment intake configured/);
   assert.doesNotMatch(node.textContent,/independent review PASS established|authorized to execute/i);
 });
});
test('Failures cannot be reported as healthy empty source or inferred progress',async()=>{
 const bad=await loadBoardNative(projectKey,async url=>url.includes('232')?
   {ok:false,status:403}:{ok:true,status:200,json:async()=>nativeMock(url)},()=> '2026-10-29T09:00:00Z');
 assert.equal(bad.status,'partial');
 assert.equal(bad.observations.length,1);
 assert.equal(bad.failures.length,1);
 const context=cycleBoardContextModel(page,{native:bad,cycleStatus:'UNMAPPED'});
 assert.equal(context.native.coverage,'PARTIAL');
 const allBad=await loadBoardNative(projectKey,async()=>({ok:false,status:429}));
 assert.equal(allBad.status,'unknown');assert.equal(allBad.observedAt,null);
 assert.equal(cycleBoardContextModel(page,{native:allBad}).native.coverage,'UNKNOWN');
 assert.equal(boardSourceConfigured('g9v35'),false);
 assert.equal((await loadBoardNative('g9v35')).status,'not_configured');
 assert.equal(cycleBoardContextModel({index:{project:{key:'g9v35'}}}).cycle.status,'UNMAPPED');
});
test('Wrong PR identity, lost head and private title fail closed',async()=>{
 const bad=await loadBoardNative(projectKey,async url=>({
   ok:true,status:200,json:async()=>({...nativeMock(url),number:777})
 }));
 assert.equal(bad.status,'unknown');assert.equal(bad.observations.length,0);
 const gone=await loadBoardNative(projectKey,async url=>({
   ok:true,status:200,json:async()=>{const x=nativeMock(url);if(x.head)x.head.sha='short';return x;}
 }));
 assert.equal(gone.status,'partial');
 assert.ok(gone.failures.some(f=>f.source.includes('/232')));
 const privateSource=await loadBoardNative(projectKey,async url=>({
   ok:true,status:200,json:async()=>({...nativeMock(url),title:'chatgpt.com/c/7e1b2311-a222-4333-8444-555566667777'})
 }));
 assert.ok(privateSource.observations.every(e=>!e.title.includes('chatgpt.com')));
});
